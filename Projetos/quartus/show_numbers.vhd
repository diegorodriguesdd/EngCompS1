ENTITY show_numbers IS
PORT(A, B, C: IN BIT;
Y: OUT BIT_VECTOR(15 DOWNTO 0));
END portas_with_vector;

ARCHITECTURE one OF show_numbers IS
SIGNAL X: BIT_VECTOR(2 DOWNTO 0);
BEGIN

X<= A & B & C;
WITH X SELECT
	Y <= "00000011111111" WHEN "0000",
		  "10011111111111" WHEN "0001",
		  "00100101111111" WHEN "0010",
		  "01100001111111" WHEN "0011",
		  "01100001111111" WHEN "0100",
		  "01100001111111" WHEN "0101",
		  "01100001111111" WHEN "0110",
		  "01100001111111" WHEN "0111",
		  "01100001111111" WHEN "1000",
		  "01100001111111" WHEN "1001",
		  "01100001111111" WHEN OTHERS,
		  
		  
END one;

