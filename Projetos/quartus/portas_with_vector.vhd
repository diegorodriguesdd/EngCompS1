ENTITY portas_with_vector IS
PORT(A, B, C: IN BIT;
Y: OUT BIT_VECTOR(13 DOWNTO 0));
END portas_with_vector;

ARCHITECTURE one OF portas_with_vector IS
SIGNAL X: BIT_VECTOR(2 DOWNTO 0);
BEGIN

X<= A & B & C;
WITH X SELECT
	Y <= "00000010000001" WHEN "000",
		  "00000010000001" WHEN "100",
		  "10011111001111" WHEN "110",
		  "10011111001111" WHEN "111",
		  "00000011001111" WHEN OTHERS;
END one;

